internal sealed class LocalizationManager : INotifyPropertyChanged
{
    private string language = "en";

    internal string Language => language;
    internal bool IsRightToLeft => language is "he" or "ar";

    public string this[string key]
    {
        get
        {
            if (Text.TryGetValue(language, out Dictionary<string, string>? table) &&
                table.TryGetValue(key, out string? value))
            {
                return value;
            }

            return Text["en"].GetValueOrDefault(key, key);
        }
    }

    internal void SetLanguage(string code)
    {
        language = Text.ContainsKey(code) ? code : "en";
        OnPropertyChanged("Item[]");
    }

    public event PropertyChangedEventHandler? PropertyChanged;

    private void OnPropertyChanged([CallerMemberName] string? name = null) => PropertyChanged?.Invoke(this, new PropertyChangedEventArgs(name));

